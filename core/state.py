"""State definitions and Pydantic models for the multi-agent system."""

from datetime import datetime
from typing import List, Literal, Optional
from pydantic import BaseModel, Field


class QueryAnalysis(BaseModel):
    """Structured extraction of customer query intent, urgency, and sentiment."""
    category: str = Field(
        ...,
        description="Ticket category, e.g. Shipping, Refund, Account, Product, Billing, General, Other"
    )
    urgency: Literal["Low", "Medium", "High"] = Field(
        ...,
        description="Urgency assessment of the issue"
    )
    sentiment: Literal["Calm", "Neutral", "Frustrated", "Angry", "Very Angry"] = Field(
        ...,
        description="Customer sentiment extracted from tone and language"
    )
    summary: str = Field(
        ...,
        description="Concise 1-line summary of the customer's problem"
    )


class KBSearchResult(BaseModel):
    """Result of searching the internal company knowledge base."""
    found: bool = Field(..., description="Whether matching passages were found")
    passages: List[str] = Field(default_factory=list, description="Extracted relevant text passages")
    sources: List[str] = Field(default_factory=list, description="Source markdown filenames used")


class ResolutionResult(BaseModel):
    """Drafted reply and confidence generated by the Resolution Agent."""
    reply: str = Field(..., description="Customer-ready professional resolution reply")
    confidence: Literal["High", "Low"] = Field(
        ...,
        description="High if grounded in knowledge base facts, Low if ungrounded/unknown"
    )


class EscalationDecision(BaseModel):
    """Escalation assessment determined by the Log Agent."""
    status: Literal["Resolved", "Escalated"] = Field(
        ...,
        description="Final resolution status"
    )
    escalation_reason: str = Field(
        default="None",
        description="Detailed reason for escalation, or 'None' if resolved"
    )


class TicketRecord(BaseModel):
    """Log record persisted to CSV log file."""
    ticket_id: str = Field(..., description="Unique ticket identifier, e.g. TKT-0001")
    timestamp: str = Field(
        default_factory=lambda: datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        description="Timestamp formatted YYYY-MM-DD HH:MM:SS"
    )
    customer_info: str = Field(..., description="Customer Name · Order ID")
    complaint: str = Field(..., description="Raw text of the customer's submitted complaint")
    category: str = Field(..., description="Issue category")
    urgency: str = Field(..., description="Urgency: Low, Medium, High")
    sentiment: str = Field(..., description="Sentiment: Calm, Neutral, Frustrated, Angry, Very Angry")
    kb_sources: str = Field(..., description="Source files referenced, e.g. shipping_policy.md")
    response: str = Field(..., description="Final response provided to customer")
    status: Literal["Resolved", "Escalated"] = Field(..., description="Resolved or Escalated")
    escalation_reason: str = Field(default="None", description="Reason if escalated, else None")

    @property
    def category_urgency_sentiment(self) -> str:
        """Formatted combined string matching assignment specification."""
        return f"{self.category} · {self.urgency} · {self.sentiment}"
